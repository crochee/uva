//! The [`Error`](enum@Error) enum — the single cross-crate error type for
//! Elysper, used by every workspace member.
//!
//! # Design: thiserror enum + boundary adapter
//!
//! Two-layer split (the axum error-handling pattern):
//!
//! - **Domain layer (this crate)** — [`Error`](enum@Error) owns the failure
//!   taxonomy: one variant per failure mode with pure payload
//!   fields. [`thiserror::Error`] generates `Display` from the
//!   per-variant `#[error("...")]` format strings and
//!   `std::error::Error::source` from the `#[from]` /
//!   `#[source]` payload fields. No hand-written message
//!   methods, no mirror `ErrorKind` classifier. The stable snake_case
//!   wire code belongs to the transport layer
//!   (`elysper_server::api::error`), not to this enum.
//! - **Transport layer (`elysper-server`)** — the `ApiError`
//!   adapter maps a variant to an HTTP status and a safe JSON
//!   envelope, and logs the full chain (operator-only detail).
//!   See `elysper_server::api::error`.
//!
//! Prefer the helper constructors ([`Error::not_found`],
//! [`Error::validation`], …) over constructing variants
//! directly.

use std::{path::PathBuf, time::Duration};

use thiserror::Error;

/// Top-level Elysper error. Returned by every fallible operation
/// across the workspace.
///
/// - `Display` (generated by thiserror) is the single-line
///   human message; the HTTP layer logs it and copies it into
///   the response envelope's `message` field.
/// - The stable snake_case wire code for telemetry tags, log
///   fields, and the envelope's `code` field is assigned at the
///   transport boundary (`elysper_server::api::error`); core owns
///   the variant taxonomy, not the encoding.
/// - `std::error::Error::source` routes through the `#[from]` /
///   `#[source]` payload fields (`Io`, `RetryExhausted`) so the
///   original cause stays reachable.
#[derive(Debug, Error)]
#[non_exhaustive]
pub enum Error {
    /// Foreign `std::io::Error`. `#[from]` generates
    /// `From<std::io::Error>` and feeds `source()`.
    #[error("I/O error: {inner}")]
    Io {
        #[from]
        inner: std::io::Error,
    },

    #[error("not found: {item}")]
    NotFound { item: String },

    #[error("already exists: {item}")]
    AlreadyExists { item: String },

    #[error("invalid item: {item}")]
    InvalidItem { item: String },

    #[error("parse error: {message}")]
    Parse { message: String },

    #[error("internal error: {message}")]
    Internal { message: String },

    #[error("unauthorized: {message}")]
    Unauthorized { message: String },

    #[error("forbidden: {message}")]
    Forbidden { message: String },

    #[error("validation error: {message}")]
    Validation { message: String },

    #[error("tool execution error: {message}")]
    ToolExecution { message: String },

    #[error("provider error: {message}")]
    Provider { message: String },

    #[error("session error: {message}")]
    Session { message: String },

    #[error("skill error: {message}")]
    Skill { message: String },

    #[error("memory error: {message}")]
    Memory { message: String },

    #[error("guardian violation: {message}")]
    GuardianViolation { message: String },

    #[error(
        "edit conflict on {}: original_hash={}, current_hash={}",
        .path.display(),
        .original_hash,
        .current_hash
    )]
    EditConflict {
        path: PathBuf,
        original_hash: u64,
        current_hash: u64,
    },

    #[error("rate limited, retry after {retry_after:?}")]
    RateLimited { retry_after: Option<Duration> },

    #[error("request failed with status {status}: {message}")]
    RequestFailed { status: u16, message: String },

    #[error("stream error: {message}")]
    Stream { message: String },

    #[error("stream error: (http_failure): {message}")]
    StreamHttpFailure { message: String },

    #[error("stream error: (protocol_error): {message}")]
    StreamProtocolError { message: String },

    #[error("stream error: (aborted): {message}")]
    StreamAborted { message: String },

    #[error("stream error: (internal): {message}")]
    StreamInternal { message: String },

    #[error("timeout: {message}")]
    Timeout { message: String },

    #[error("retry exhausted after {attempts} attempts: {last_error}")]
    RetryExhausted {
        attempts: u32,
        #[source]
        last_error: Box<Error>,
    },

    #[error("model not found: {message}")]
    ModelNotFound { message: String },

    #[error("model unavailable: {message}")]
    ModelUnavailable { message: String },

    #[error("config error: {message}")]
    Config { message: String },

    #[error("model router error: {message}")]
    Router { message: String },

    #[error("context error: {message}")]
    Context { message: String },

    #[error("telemetry error: {message}")]
    Telemetry { message: String },

    #[error("multiagent error: {message}")]
    Multiagent { message: String },

    #[error("evaluation error: {message}")]
    Evaluation { message: String },

    #[error(
        "context overflow: {actual_tokens} tokens used, limit is {limit_tokens}"
    )]
    ContextOverflow {
        limit_tokens: u64,
        actual_tokens: u64,
    },

    #[error(
        "doom loop detected on '{tool_name}' after {iterations} iterations"
    )]
    DoomLoop { tool_name: String, iterations: u32 },

    #[error("prompt injection detected in {input_source}: pattern '{pattern}'")]
    PromptInjection {
        input_source: String,
        pattern: String,
    },
}

impl Error {
    // -----------------------------------------------------------------
    // Helper constructors.
    //
    // Kept constructors are those actually used by workspace
    // production code (grep-verified). Other variants still exist
    // on the enum to keep the wire-code table stable; their
    // payloads can be constructed directly when needed.
    // -----------------------------------------------------------------

    /// Construct an [`Error::NotFound`].
    pub fn not_found(item: impl Into<String>) -> Self {
        Self::NotFound { item: item.into() }
    }

    /// Construct an [`Error::AlreadyExists`].
    pub fn already_exists(item: impl Into<String>) -> Self {
        Self::AlreadyExists { item: item.into() }
    }

    /// Construct an [`Error::InvalidItem`].
    pub fn invalid_item(item: impl Into<String>) -> Self {
        Self::InvalidItem { item: item.into() }
    }

    /// Construct an [`Error::Parse`].
    pub fn parse(message: impl Into<String>) -> Self {
        Self::Parse {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Internal`].
    pub fn internal(message: impl Into<String>) -> Self {
        Self::Internal {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Validation`].
    pub fn validation(message: impl Into<String>) -> Self {
        Self::Validation {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Provider`].
    pub fn provider(message: impl Into<String>) -> Self {
        Self::Provider {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Session`].
    pub fn session(message: impl Into<String>) -> Self {
        Self::Session {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Forbidden`].
    pub fn forbidden(message: impl Into<String>) -> Self {
        Self::Forbidden {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Timeout`].
    pub fn timeout(message: impl Into<String>) -> Self {
        Self::Timeout {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Config`].
    pub fn config(message: impl Into<String>) -> Self {
        Self::Config {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Telemetry`].
    pub fn telemetry(message: impl Into<String>) -> Self {
        Self::Telemetry {
            message: message.into(),
        }
    }

    /// Construct an [`Error::Stream`].
    pub fn stream(message: impl Into<String>) -> Self {
        Self::Stream {
            message: message.into(),
        }
    }

    /// Construct an [`Error::RateLimited`].
    pub fn rate_limited(retry_after: Option<Duration>) -> Self {
        Self::RateLimited { retry_after }
    }

    /// Construct an [`Error::RequestFailed`].
    pub fn request_failed(status: u16, message: impl Into<String>) -> Self {
        Self::RequestFailed {
            status,
            message: message.into(),
        }
    }

    /// Construct an [`Error::EditConflict`].
    pub fn edit_conflict(
        path: impl Into<PathBuf>,
        original_hash: u64,
        current_hash: u64,
    ) -> Self {
        Self::EditConflict {
            path: path.into(),
            original_hash,
            current_hash,
        }
    }

    /// Construct an [`Error::ContextOverflow`].
    pub fn context_overflow(limit_tokens: u64, actual_tokens: u64) -> Self {
        Self::ContextOverflow {
            limit_tokens,
            actual_tokens,
        }
    }

    /// Construct an [`Error::DoomLoop`].
    pub fn doom_loop(tool_name: impl Into<String>, iterations: u32) -> Self {
        Self::DoomLoop {
            tool_name: tool_name.into(),
            iterations,
        }
    }

    /// Construct an [`Error::PromptInjection`].
    pub fn prompt_injection(
        source: impl Into<String>,
        pattern: impl Into<String>,
    ) -> Self {
        Self::PromptInjection {
            input_source: source.into(),
            pattern: pattern.into(),
        }
    }

    /// Construct an [`Error::RetryExhausted`].
    pub fn retry_exhausted(attempts: u32, last_error: Error) -> Self {
        Self::RetryExhausted {
            attempts,
            last_error: Box::new(last_error),
        }
    }

    /// Construct an [`Error::StreamHttpFailure`] (upstream
    /// HTTP transport failure — connection, TLS, status).
    pub fn stream_http_failure(message: impl Into<String>) -> Self {
        Self::StreamHttpFailure {
            message: message.into(),
        }
    }

    /// Construct an [`Error::StreamAborted`] (caller cancelled
    /// the stream).
    pub fn stream_aborted(message: impl Into<String>) -> Self {
        Self::StreamAborted {
            message: message.into(),
        }
    }

    // -----------------------------------------------------------------
    // Classification
    // -----------------------------------------------------------------

    /// Returns true if this error is retryable based on its type
    /// or status code.
    pub fn is_retryable(&self) -> bool {
        match self {
            Self::RequestFailed { status, .. } => {
                matches!(status, 429 | 500 | 502 | 503 | 504)
            }
            Self::Stream { .. }
            | Self::StreamHttpFailure { .. }
            | Self::StreamProtocolError { .. }
            | Self::StreamInternal { .. } => true,
            Self::Timeout { .. } => true,
            Self::RateLimited { .. } => true,
            _ => false,
        }
    }

    /// Returns true if this error indicates rate limiting.
    pub fn is_rate_limited(&self) -> bool {
        matches!(self, Self::RateLimited { .. })
    }

    // -----------------------------------------------------------------
    // Wire code
    //
    // The canonical snake_case wire code is owned by the server
    // boundary (`From<elysper_core::Error> for AppError` in
    // `elysper-server`), which inlines `(status, code)` per
    // variant. Core is intentionally dumb: it owns the variant
    // taxonomy, the Display strings, and the source-chain
    // routing; everything transport-specific lives one layer
    // up.
    // -----------------------------------------------------------------
}

// -----------------------------------------------------------------------------
// From impls for foreign error types.
//
// `From<std::io::Error>` is generated by thiserror's `#[from]` on
// the `Io` variant.
//
// `From<reqwest::Error>` is gated on the `reqwest` feature: it is the
// only thing in this crate that needs an HTTP client, and a consumer
// that never speaks HTTP should not compile one.
// -----------------------------------------------------------------------------

#[cfg(feature = "reqwest")]
impl From<reqwest::Error> for Error {
    fn from(e: reqwest::Error) -> Self {
        // Classify via the reqwest API surface
        // (`is_timeout` / `is_connect` / …) so callers keep the
        // transport-specific semantics.
        let msg = e.to_string();
        if e.is_timeout() {
            Self::Timeout { message: msg }
        } else if e.is_connect() {
            Self::Stream { message: msg }
        } else if e.is_request() && e.is_redirect() {
            Self::RequestFailed {
                status: 0,
                message: msg,
            }
        } else {
            Self::Internal { message: msg }
        }
    }
}

impl From<serde_json::Error> for Error {
    fn from(e: serde_json::Error) -> Self {
        Self::Parse {
            message: e.to_string(),
        }
    }
}

impl From<serde_yaml::Error> for Error {
    fn from(e: serde_yaml::Error) -> Self {
        Self::Parse {
            message: format!("yaml error: {e}"),
        }
    }
}

